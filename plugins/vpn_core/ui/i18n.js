  // The page follows the host locale; outside the page (tests, tools) it defaults to Chinese.
  function locale() {
    const host = root.VeerPluginHost;
    return host && host.locale === 'en-US' ? 'en-US' : 'zh-CN';
  }
  function t(key, params) {
    const dict = messages[locale()], fallback = messages['zh-CN'];
    const own = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
    const text = own(dict, key) ? dict[key] : own(fallback, key) ? fallback[key] : key;
    return params ? text.replace(/\{\{(\w+)\}\}/g, (_, name) => params[name] == null ? '' : String(params[name])) : text;
  }
